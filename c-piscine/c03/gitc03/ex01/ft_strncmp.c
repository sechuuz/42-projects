int	ft_strncmp(char *s1, char *s2, unsigned int n)
{
	unsigned int	i;

	i = 0;
	while (i < n && (s1[i] != '\0' && (s1[i] == s2[i])))
	{
		i++;
	}
	if (s1[i] == s2[i] || n <= 0 || n <= i)
	{
		return (0);
	}
	else
	{
		return (s1[i] - s2[i]);
	}
}
